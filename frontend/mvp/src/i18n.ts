export type MessageKey = keyof typeof messages.zh;

export function translate(
  language: Language,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  let message: string = messages[language][key];
  if (!values) return message;
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{{${name}}}`, String(value));
  }
  return message;
}

export function categoryOptions(language: Language, type: "notes" | "projects") {
  const keys: MessageKey[] = type === "notes"
    ? ["categoryAll", "categoryArchitecture", "categorySearch", "categoryContent", "categoryFrontend", "categoryEngineering"]
    : ["categoryAll", "categoryPersonal", "categoryBackend", "categoryTooling"];
  return keys.map((key) => ({ key, label: translate(language, key) }));
}
